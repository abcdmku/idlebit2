// Generates the task icon data (types.ts, icons-<type>.ts) from the art sources in ./art.
// Rerun after editing the art: node src/render/core/familyIcons/generate.mjs
// It refuses to write if any glyph leaves its frame's plate, a band has no type, or two icons match.
import { readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { BAND } from './art/catalog.mjs';
import { BAND_TYPE, TYPES, TYPE_ORDER, buildIcons, plateOf } from './art/build.mjs';

const { types, families, errors } = buildIcons();
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const dir = new URL('./', import.meta.url), head = '// Generated by generate.mjs from ./art. Do not edit.\n';
const q = (s) => `'${s.replace(/'/g, "\\'")}'`;
const block = (rows, pad) => `[\n${rows.map((r) => `${pad}  ${q(r)},`).join('\n')}\n${pad}]`;

for (const f of readdirSync(dir)) if (/^icons-\w+\.ts$/.test(f) || f === 'bands.ts') unlinkSync(new URL(f, dir));
for (const t of TYPE_ORDER) {
  let out = `${head}/** ${TYPES[t].name} family icons: 16 rows of 16, see types.ts for the chars. */\n`;
  out += 'export const ICONS: Readonly<Record<string, readonly string[]>> = {\n';
  for (const f of families.filter((x) => x.type === t)) out += `  ${f.key}: ${block(f.rows, '  ')},\n`;
  writeFileSync(new URL(`icons-${t}.ts`, dir), out + '};\n');
}

let s = `${head}import type { BandId } from '../../../game';\n\n`;
s += `/** The player-facing task types (D23), in display order. */\nexport type TaskType = ${TYPE_ORDER.map(q).join(' | ')};\n`;
s += `export const TASK_TYPES: readonly TaskType[] = [${TYPE_ORDER.map(q).join(', ')}];\n`;
s += '/** a: the type colour, d: shade, l: light, k: the dark plate icons sit on. */\n';
s += 'export interface TypeStyle { readonly name: string; readonly bands: readonly BandId[]; readonly a: string; readonly d: string; readonly l: string; readonly k: string }\n';
s += 'export const TYPE: Readonly<Record<TaskType, TypeStyle>> = {\n';
for (const t of TYPE_ORDER) { const y = TYPES[t]; s += `  ${t}: { name: ${q(y.name)}, bands: [${y.bands.map(q).join(', ')}], a: ${q(y.a)}, d: ${q(y.d)}, l: ${q(y.l)}, k: ${q(plateOf(t))} },\n`; }
s += '};\n/** Every catalog band belongs to exactly one type. */\nexport const BAND_TYPE: Readonly<Record<BandId, TaskType>> = {\n';
for (const [b, t] of Object.entries(BAND_TYPE)) s += `  ${b}: ${q(t)},\n`;
s += '};\nexport const BAND_ORDER: readonly BandId[] = [' + Object.keys(BAND_TYPE).map(q).join(', ') + '];\n';
s += 'export const BAND_NAME: Readonly<Record<BandId, string>> = {\n';
for (const b of Object.keys(BAND_TYPE)) s += `  ${b}: ${q(BAND[b].name)},\n`;
s += '};\n/**\n * Icon chars: . clear, o ink outline, k plate, l/a/d the type ramp, w white highlight.\n';
s += ' * Every icon is 16×16: a 14×14 silhouette with its outline baked into the 1 px margin.\n */\n';
s += 'export const TYPE_ICONS: Readonly<Record<TaskType, readonly string[]>> = {\n';
for (const t of types) s += `  ${t.key}: ${block(t.rows, '  ')},\n`;
writeFileSync(new URL('types.ts', dir), s + '};\n');
console.log(`generated ${types.length} type icons and ${families.length} family icons`);
